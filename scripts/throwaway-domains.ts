/**
 * Refreshes src/server/lib/throwaway-domains.generated.ts from the disposable-email-domains
 * blocklist (github.com/disposable-email-domains/disposable-email-domains), the throwaway inbox
 * services new accounts can't be opened with (lib/throwaway-email.ts). Relays that forward to a
 * real inbox (iCloud Hide My Email, DuckDuckGo, Firefox Relay, SimpleLogin) are not on it.
 *
 *   npm run throwaway-domains
 */
import { writeFileSync } from 'node:fs';

const SOURCE = 'https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf';
const OUT = new URL('../src/server/lib/throwaway-domains.generated.ts', import.meta.url);

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`${SOURCE}: ${res.status}`);
const domains = [...new Set((await res.text()).split('\n').map((l) => l.trim().toLowerCase()).filter((l) => l && !l.startsWith('#')))].sort();
if (domains.length < 1000) throw new Error(`only ${domains.length} domains in ${SOURCE}; not replacing the list`);

writeFileSync(
  OUT,
  `// Generated by npm run throwaway-domains from ${SOURCE}.\n// Edit scripts/throwaway-domains.ts, not this file.\nexport const THROWAWAY_DOMAINS = ${JSON.stringify(domains.join('\n'))};\n`,
);
console.log(`${domains.length} throwaway domains written to ${OUT.pathname}`);
